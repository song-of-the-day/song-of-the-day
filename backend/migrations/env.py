"""Alembic environment, driven by Flask-Migrate (``flask db ...``) inside an app context.

Migrations run on the application's engine against the model metadata. Autogenerate
compares column types and server defaults, the same options the migration tests use,
and skips writing a revision when nothing changed.
"""

from __future__ import annotations

import logging
from collections.abc import Iterable

from alembic import context
from alembic.operations.ops import MigrationScript
from alembic.runtime.migration import MigrationContext

import sotd.models  # noqa: F401  (registers every table on the metadata)
from sotd.extensions import db

logger = logging.getLogger("alembic.env")


def _skip_empty_revisions(
    _migration_context: MigrationContext,
    _revision: str | Iterable[str | None] | Iterable[str],
    directives: list[MigrationScript],
) -> None:
    """Drop an autogenerated revision that contains no operations."""
    cmd_opts = context.config.cmd_opts
    if getattr(cmd_opts, "autogenerate", False) and directives[0].upgrade_ops_list[0].is_empty():
        directives.clear()
        logger.info("No changes in schema detected.")


def run_migrations_offline() -> None:
    """Emit the migration SQL as a script instead of executing it."""
    context.configure(
        url=db.engine.url.render_as_string(hide_password=False),
        target_metadata=db.metadata,
        literal_binds=True,
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run the migrations on a connection from the application's engine."""
    with db.engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=db.metadata,
            process_revision_directives=_skip_empty_revisions,
            compare_type=True,
            compare_server_default=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
